import fs from 'node:fs';
import internals from '@prisma/internals';
const { getDMMF } = internals;

let schema = fs.readFileSync('prisma/schema.prisma', 'utf8');
schema = schema.replace('provider = "prisma-client-js"', 'provider = "prisma-client"\n  output = "../cloudflare/generated/client"\n  engineType = "client"\n  runtime = "cloudflare"');
schema = schema.replace('provider = "postgresql"', 'provider = "sqlite"').replace('env("DATABASE_URL")', '"file:./local.db"');
// Aadhaar is looked up as a unique key by the existing member routes.
schema = schema.replace(/aadhaar\s+String\?/, 'aadhaar             String? @unique');
schema = schema.replace('  @@index([email])', '  @@index([email, used, createdAt])');
schema = schema.replace('  createdAt  DateTime @default(now())\n}', '  createdAt  DateTime @default(now())\n  @@index([memberId, date])\n}');
fs.writeFileSync('prisma/schema.d1.prisma', '// Generated by scripts/prepare-d1.mjs\n' + schema);
const { datamodel } = await getDMMF({ datamodel: schema });
const models = Object.fromEntries(datamodel.models.map(m => [m.name[0].toLowerCase() + m.name.slice(1), {
  table: m.name,
  fields: m.fields.filter(f => f.kind !== 'object').map(f => ({ name: f.name, type: f.type, required: f.isRequired, id: f.isId, updated: f.isUpdatedAt, default: f.default })),
}]));
fs.writeFileSync('cloudflare/models.json', JSON.stringify(models, null, 2) + '\n');
